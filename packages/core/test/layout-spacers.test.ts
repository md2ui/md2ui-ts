test("defaults double per step, and follow the group gap along their direction", () => {
  for (const [step, px] of [
    ["small", 8],
    ["medium", 16],
    ["large", 32],
  ] as const) {
    expect(spacerSize(null, step, "col", 0)).toBe(px);
  }
  const t = parseTheme(
    "## Styling & Spacing\n### Elements\nRow spacing: 10\nCol spacing: 10\nGroup row spacing: 20\nGroup col spacing: 16\n",
  );
  expect((["small", "medium", "large"] as const).map((s) => spacerSize(t, s, "col", 0))).toEqual([
    16, 32, 64,
  ]);
  expect((["small", "medium", "large"] as const).map((s) => spacerSize(t, s, "row", 0))).toEqual([
    20, 30, 40,
  ]);
});

test("the nearest level wins, then root, then default; an axis key beats the plain key on its axis only", () => {
  const t = parseTheme(
    "## Styling & Spacing\n### Root\nSpacer large: 48\nSpacer small row: 12\n### Heading 2\nSpacer large: 64\n### Image Cards\nSpacer medium: 200\n",
  );
  expect(spacerSize(t, "large", "col", 2)).toBe(64);
  expect(spacerSize(t, "large", "col", 3)).toBe(48);
  expect(spacerSize(t, "medium", "col", 2)).toBe(16);
  expect(spacerSize(t, "medium", "col", 2, null, true)).toBe(200);
  expect(spacerSize(t, "small", "row", 0)).toBe(12);
  expect(spacerSize(t, "small", "col", 0)).toBe(8);
});

// A tree in one line: a leaf is its content id (or "sp"), a container [type, ratios, ...children].
const shape = (n: LayoutNode): unknown =>
  n.type === "-"
    ? n.render_properties?.["spacer"]
      ? "sp"
      : n.content_id
    : [n.type, n.ratios, ...n.children.map(shape)];
const leaf = (id: string): LayoutNode => layoutNode("-", [], [], { content_id: id });
const sp = (axis = "col", binds: string | null = null): LayoutNode =>
  layoutNode("-", [], [], { render_properties: { spacer: { axis, size: 8, binds } } });
const row = (...kids: LayoutNode[]): LayoutNode =>
  layoutNode(
    "row",
    kids.map(() => 1),
    kids,
  );
const col = (...kids: LayoutNode[]): LayoutNode =>
  layoutNode(
    "col",
    kids.map(() => 1),
    kids,
  );

test("foldRowSpacers moves vertical spacers into the cell they bind to", () => {
  const cases: [string, LayoutNode, unknown][] = [
    ["only spacers (kept as written)", row(sp(), sp()), ["row", [1.0, 1.0], "sp", "sp"]],
    [
      "leading spacer enters the next cell",
      row(sp(), leaf("a"), leaf("b")),
      ["row", [1.0, 1.0], ["col", [1.0, 1.0], "sp", "a"], "b"],
    ],
    [
      "trailing spacer enters the last cell",
      row(leaf("a"), leaf("b"), sp()),
      ["row", [1.0, 1.0], "a", ["col", [1.0, 1.0], "b", "sp"]],
    ],
    [
      "a spacer that binds back stacks under the cell before it",
      row(leaf("a"), sp("col", "prev"), leaf("b")),
      ["row", [1.0, 1.0], ["col", [1.0, 1.0], "a", "sp"], "b"],
    ],
    [
      "a leading spacer that binds back has no cell before it",
      row(sp("col", "prev"), leaf("a")),
      ["row", [1.0], ["col", [1.0, 1.0], "sp", "a"]],
    ],
    [
      "a column cell is stacked in place",
      row(sp(), col(leaf("x"), leaf("y")), leaf("b"), sp()),
      ["row", [1.0, 1.0], ["col", [1.0, 1.0, 1.0], "sp", "x", "y"], ["col", [1.0, 1.0], "b", "sp"]],
    ],
    [
      "consecutive spacers go to the same cell",
      row(leaf("a"), sp(), sp(), leaf("b"), sp("col", "edge")),
      ["row", [1.0, 1.0], "a", ["col", [1.0, 1.0, 1.0, 1.0], "sp", "sp", "b", "sp"]],
    ],
    [
      "a horizontal spacer is a cell of its row",
      row(sp("row"), leaf("a")),
      ["row", [1.0, 1.0], "sp", "a"],
    ],
    [
      "rows fold bottom-up inside other containers",
      col(row(sp(), leaf("a")), row(leaf("b"), leaf("c"))),
      [
        "col",
        [1.0, 1.0],
        ["row", [1.0], ["col", [1.0, 1.0], "sp", "a"]],
        ["row", [1.0, 1.0], "b", "c"],
      ],
    ],
    [
      "a row without spacers is untouched",
      row(leaf("a"), leaf("b")),
      ["row", [1.0, 1.0], "a", "b"],
    ],
  ];
  for (const [label, tree, want] of cases) {
    foldRowSpacers(tree);
    expect(shape(tree), label).toEqual(want);
  }
});

test("foldRowSpacers keeps each surviving cell's ratio; a cell without one takes 1", () => {
  const withRatios = (ratios: number[], ...kids: LayoutNode[]): LayoutNode => {
    const r = row(...kids);
    r.ratios = ratios;
    return r;
  };
  const a = withRatios([1, 2, 3], sp(), leaf("a"), leaf("b"));
  foldRowSpacers(a);
  expect(shape(a)).toEqual(["row", [2.0, 3.0], ["col", [1.0, 1.0], "sp", "a"], "b"]);
  const b = withRatios([], sp(), leaf("a"), leaf("b"));
  foldRowSpacers(b);
  expect(shape(b)).toEqual(["row", [1.0, 1.0], ["col", [1.0, 1.0], "sp", "a"], "b"]);
  // md2ui's `test_a_row_short_of_ratios_keeps_every_cell`.
  const c = withRatios([1, 2], leaf("a"), sp(), leaf("b"), leaf("c"));
  foldRowSpacers(c);
  expect(shape(c)).toEqual(["row", [1.0, 1.0, 1.0], "a", ["col", [1.0, 1.0], "sp", "b"], "c"]);
});
