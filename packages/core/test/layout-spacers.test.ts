// md2ui `test_an_unstated_spacer_never_measures_less_than_its_floor`.
test("an unstated spacer never measures less than its floor", () => {
  expect(SPACER_FLOORS).toEqual({
    col: { small: 8, medium: 16, large: 32 },
    row: { small: 8, medium: 12, large: 16 },
  });
  const zero = parseTheme(
    "# T\n## Styling & Spacing\n### Root\nSpacing: 0\n### Elements\nRow spacing: 0\nCol spacing: 0\nGroup spacing: 0\n",
  );
  const steps = ["small", "medium", "large"] as const;
  expect(steps.map((s) => spacerSize(zero, s, "col", 0))).toEqual([8, 16, 32]);
  expect(steps.map((s) => spacerSize(zero, s, "row", 0))).toEqual([8, 12, 16]);
  const wide = parseTheme("# T\n## Styling & Spacing\n### Elements\nGroup spacing: 18\n");
  expect(spacerSize(wide, "large", "col", 0)).toBe(72);
  const stated = parseTheme("# T\n## Styling & Spacing\n### Root\nSpacer small: 0\n");
  expect(spacerSize(stated, "small", "col", 0)).toBe(0);
});

