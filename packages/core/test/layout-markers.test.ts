// Ported from md2ui tests/layout_marker_tests.py (test_style_selection, ..._do_not_cross_background_levels, test_task_marker_falls_back...).
const LEVELS = "## Styling & Spacing\n### Heading 2\n#### Marker\nFont size: 64\nSpace: 32\n";
const PLAIN = "## Styling & Spacing\n### Numbered Lists\n#### Marker\nFont size: 28\nSpace: 16\n";

test("a heading ordinal takes its level's marker, a plain one the Numbered Lists marker", () => {
  const both = parseTheme(`${PLAIN}${LEVELS}`);
  expect(numberedStyle(2, both).text_style?.font_size).toBe(64);
  expect(numberedStyle(null, both).text_style?.font_size).toBe(28);
});

test("numbered marker styles stay on their exact background level", () => {
  expect(numberedStyle(2, parseTheme(PLAIN)).text_style).toBeNull();
  expect(numberedStyle(null, parseTheme(LEVELS)).text_style).toBeNull();
  expect(numberedStyle(2, parseTheme("")).text_style).toBeNull();
});

test("a task marker overrides, then falls back to the Unordered Lists marker", () => {
  const inherited = parseTheme(
    "## Styling & Spacing\n### Unordered Lists\n#### Marker\nShape: circle\n",
  );
  expect(bulletStyle("task_open", inherited)).toBe(inherited.unordered_lists.marker);
  const own = parseTheme(
    "## Styling & Spacing\n### Unordered Lists\n#### Marker\nShape: circle\n### Task Lists\n#### Marker\nShape: square\n",
  );
  expect(bulletStyle("task_open", own)?.shape).toBe("square");
  expect(bulletStyle("ordered_item", own)).toBeNull();
});

