// Generate C1 types from md2ui's grouping-ast.schema.json.
// Takes the schema path as a command-line argument.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { argv, exit } from "node:process";

import { compile } from "json-schema-to-typescript";

const bin = (tool: string): string => `node_modules/.bin/${tool}`;

async function main(): Promise<number> {
  const schemaPath = argv[2];
  if (!schemaPath) {
    console.error("Usage: node scripts/generate-c1.ts <schema-path>");
    return 1;
  }

  const resolvedSchemaPath = resolve(schemaPath);
  const outputPath = resolve("packages/contracts/src/c1-grouping-ast.ts");

  try {
    // Read and parse the schema
    const schemaText = readFileSync(resolvedSchemaPath, "utf-8");
    const schema = JSON.parse(schemaText) as Record<string, unknown>;

    // Create modified versions of the schema that reference node and data_point definitions
    const schemaForNode = {
      ...schema,
      title: "GroupingNode",
      $ref: "#/$defs/node",
    };

    const schemaForDataPoint = {
      ...schema,
      title: "GroupingDataPoint",
      $ref: "#/$defs/data_point",
    };

    // Compile both types separately
    const nodeType = await compile(schemaForNode, "GroupingNode", {
      bannerComment: "",
      declareExternallyReferenced: true,
      additionalProperties: false,
    });

    const dataPointType = await compile(schemaForDataPoint, "GroupingDataPoint", {
      bannerComment: "",
      declareExternallyReferenced: true,
      additionalProperties: false,
    });

    // Extract just the interface definitions
    const nodeInterfaceMatch = nodeType.match(/export interface GroupingNode[\s\S]*?^\}/m);
    const dataPointInterfaceMatch = dataPointType.match(
      /export interface GroupingDataPoint[\s\S]*?^\}/m,
    );

    if (!nodeInterfaceMatch || !dataPointInterfaceMatch) {
      console.error("Failed to extract type definitions from generated schema");
      console.error("Node type output:", nodeType.substring(0, 200));
      console.error("DataPoint type output:", dataPointType.substring(0, 200));
      return 1;
    }

    let nodeInterface = nodeInterfaceMatch[0];
    let dataPointInterface = dataPointInterfaceMatch[0];

    // Keep index signatures in nested objects (they're allowed for additional properties)
    // They're only removed from the top-level type itself, which is handled by additionalProperties: false
    // Biome will complain about them, but we can suppress those warnings

    // Fix recursive reference: Node[] should be GroupingNode[]
    nodeInterface = nodeInterface.replace(/\bNode\[\]/g, "GroupingNode[]");

    // Fix data point reference: DataPoint should be GroupingDataPoint
    nodeInterface = nodeInterface.replace(/\bDataPoint\b/g, "GroupingDataPoint");

    // Replace fingerprint_hash type: number | null -> bigint | null
    // Match both with and without optional (? )
    nodeInterface = nodeInterface.replace(
      /fingerprint_hash\??: number \| null;/g,
      `fingerprint_hash: bigint | null; // values can exceed Number.MAX_SAFE_INTEGER (2^53)`,
    );

    // Replace problematic {} and index signature types:
    // These should be Record types instead
    // Match: property?: { \n    [k: string]: <type>; \n  }; patterns
    nodeInterface = nodeInterface.replace(
      /child_type_counts\?: \{\s*\[\s*k:\s*string\s*\]:\s*number\s*;\s*\};/g,
      "child_type_counts?: Record<string, number>;",
    );
    dataPointInterface = dataPointInterface.replace(
      /value:\s*\{\s*\[\s*k:\s*string\s*\]:\s*unknown\s*;\s*\};/g,
      "value: unknown;",
    );

    // Build the final output with header
    const header = `// C1 — the grouping AST: md2ui's MarkdownGroupNode.to_dict(). Not public.
//
// Generated by \`pnpm generate:c1 <schema>\` from md2ui's grouping-ast.schema.json;
// do not edit by hand.
// biome-ignore-all lint/complexity/noBannedTypes: the schema's free-form objects come out as \`{}\`.

`;

    const finalOutput = `${header}${nodeInterface}\n\n${dataPointInterface}\n`;

    writeFileSync(outputPath, finalOutput);

    // Format with biome
    const biomeResult = spawnSync(bin("biome"), ["format", "--write", outputPath], {
      stdio: "inherit",
    });

    if (biomeResult.status !== 0) {
      console.error("Biome formatting failed");
      return 1;
    }

    console.log(`Generated ${outputPath}`);
    return 0;
  } catch (error) {
    console.error("Generation failed:", error);
    return 1;
  }
}

exit(await main());
